"""
make_replicate_configs.py

Expand one base config into R replicate configs that differ only in the data
seed and in the output identity, so the replicates of a setting are independent
datasets that can be averaged into an error bar. For each replicate it bumps
`simulation.seed`, gives a unique `experiment_name`, and repoints the
`inference.data.*` paths to the new per-replicate data directory. The
`simulation.signatures.path` is left untouched so every replicate loads the same
frozen signature matrix; only the forest and activities vary.

Run once per setting (per overlap rho or per tree count); point each invocation
at that setting's base config and pass `--setting-value` so the aggregation
manifest groups correctly. Use `--append` to accumulate one manifest across
settings.

Outputs (to --outdir)
    <experiment_name>_rep<r>.yaml   one config per replicate
    manifest_configs.txt            config paths, one per line (for the sbatch
                                    array; set --array=0-(N-1))
    manifest_agg.csv                setting, rep, dir for aggregate_replicates.py
                                    (dir is the per-replicate results directory)

Usage
    python scripts/make_replicate_configs.py \
        --base configs/config_denovo_corr_0.3_20_trees_ilr.yaml \
        --n-reps 15 --setting-value 0.3 --draws 2000 --tune 2000 \
        --outdir configs/overlap_sweep
"""

from __future__ import annotations

import argparse
import copy
from pathlib import Path

import yaml


def repoint_data(data: dict, results_dir: str, new_name: str) -> dict:
    """Point every data file at this replicate's own generated directory,
    <results_dir>/<new_name>/<filename>. Reconstructing from the directory rather
    than string-replacing the old name makes this immune to a base config whose
    data paths do not already match its experiment_name (a common copy-paste
    slip), and to one that points at a different dataset entirely."""
    base_dir = f"{results_dir.rstrip('/')}/{new_name}"
    return {
        k: (f"{base_dir}/{Path(v).name}" if isinstance(v, str) else v)
        for k, v in data.items()
    }


def make_one(
    base: dict, rep: int, seed: int, new_name: str, draws: int | None, tune: int | None
) -> dict:
    """One replicate config: bumped seed, name, repointed data paths, optional
    sampler overrides. Everything else copied from the base."""
    cfg = copy.deepcopy(base)
    cfg["experiment_name"] = new_name
    cfg["simulation"]["seed"] = seed
    cfg["inference"]["data"] = repoint_data(
        cfg["inference"]["data"], base["simulation"]["results_dir"], new_name
    )
    if draws is not None:
        cfg["inference"]["draws"] = draws
    if tune is not None:
        cfg["inference"]["tune"] = tune
    return cfg


def write_config(cfg: dict, outdir: Path, header: str) -> Path:
    """Dump one config, preserving key order, with a short generated header."""
    path = outdir / f"{cfg['experiment_name']}.yaml"
    with path.open("w") as f:
        f.write(header)
        yaml.safe_dump(cfg, f, sort_keys=False, default_flow_style=False)
    return path


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--base", required=True)
    ap.add_argument("--n-reps", type=int, required=True)
    ap.add_argument(
        "--base-seed",
        type=int,
        default=None,
        help="seed of replicate 0; default is the base config's seed. "
        "replicate r uses base-seed + r",
    )
    ap.add_argument(
        "--setting-value",
        default=None,
        help="the controllable-axis value for this base (e.g. the "
        "overlap rho or the tree count); tags the agg manifest",
    )
    ap.add_argument("--draws", type=int, default=None)
    ap.add_argument("--tune", type=int, default=None)
    ap.add_argument("--outdir", default="configs/replicates")
    ap.add_argument(
        "--append",
        action="store_true",
        help="append to existing manifests instead of overwriting",
    )
    a = ap.parse_args()

    base = yaml.safe_load(Path(a.base).read_text())
    old_name = base["experiment_name"]
    base_seed = (
        a.base_seed if a.base_seed is not None else int(base["simulation"]["seed"])
    )
    setting = a.setting_value if a.setting_value is not None else old_name
    res_root = base["inference"]["results_dir"].rstrip("/")

    out = Path(a.outdir)
    out.mkdir(parents=True, exist_ok=True)
    cfg_lines, agg_rows, agg_rows_nmf = [], [], []
    for r in range(a.n_reps):
        new_name = f"{old_name}_rep{r}"
        seed = base_seed + r
        cfg = make_one(base, r, seed, new_name, a.draws, a.tune)
        header = (
            f"# generated by make_replicate_configs.py from {a.base}\n"
            f"# replicate {r}, seed {seed}, setting {setting}\n"
        )
        path = write_config(cfg, out, header)
        cfg_lines.append(str(path))
        agg_rows.append(f"{setting},{r},{res_root}/{new_name}/recovery")
        agg_rows_nmf.append(f"{setting},{r},{res_root}/{new_name}/nmf")

    mode = "a" if a.append else "w"
    cfg_manifest = out / "manifest_configs.txt"
    agg_manifest = out / "manifest_agg.csv"
    nmf_manifest = out / "manifest_agg_nmf.csv"
    with cfg_manifest.open(mode) as f:
        f.write("\n".join(cfg_lines) + "\n")
    for man, rows in ((agg_manifest, agg_rows), (nmf_manifest, agg_rows_nmf)):
        write_header = not (a.append and man.exists())
        with man.open(mode) as f:
            if write_header:
                f.write("setting,rep,dir\n")
            f.write("\n".join(rows) + "\n")

    print(f"wrote {a.n_reps} configs to {out}")
    print(f"  sbatch manifest:      {cfg_manifest}  (--array=0-{a.n_reps - 1})")
    print(f"  aggregation manifest: {agg_manifest} (Tree-HDP), {nmf_manifest} (NMF)")
    print(f"  seeds: {base_seed}..{base_seed + a.n_reps - 1}, setting={setting}")


if __name__ == "__main__":
    main()
